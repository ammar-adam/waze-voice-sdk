/* Backseat. Renders the voices from voices.json, plays previews, installs.

   voices.json is the single source for every UUID. lines.json is generated by
   scripts/build_previews.py from the live presets, so the words shown under a
   playing clip are the words the pack actually says. */

(function () {
  "use strict";

  var PENDING_KEY = "backseat.pending";
  var PENDING_MAX_AGE = 7 * 24 * 3600 * 1000;

  var CLIPS = [
    { id: "turn", cap: "¼ mi · Turn right",
      icon: '<path d="M6 20v-7a5 5 0 0 1 5-5h7"/><path d="m15 4 4 4-4 4"/>' },
    { id: "reroute", cap: "Recalculating",
      icon: '<path d="M20 11a8 8 0 1 0-2.3 5.7"/><path d="M20 4v7h-7"/>' },
    { id: "arrive", cap: "Arrived",
      icon: '<path d="M12 21s-6-5.4-6-10a6 6 0 0 1 12 0c0 4.6-6 10-6 10z"/><circle cx="12" cy="11" r="2"/>' }
  ];

  var ARROW = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h13"/><path d="m12 6 6 6-6 6"/></svg>';

  var params = new URLSearchParams(location.search);
  var utm = {
    utm_source: params.get("utm_source") || "",
    utm_medium: params.get("utm_medium") || "",
    utm_campaign: params.get("utm_campaign") || ""
  };
  var device = window.isPhone ? "phone" : "desktop";
  var inapp = window.inAppBrowser || "";

  function store(get, value) {
    try {
      if (get) return JSON.parse(localStorage.getItem(PENDING_KEY) || "null");
      if (value === null) localStorage.removeItem(PENDING_KEY);
      else localStorage.setItem(PENDING_KEY, JSON.stringify(value));
    } catch (e) { return null; }
    return null;
  }

  function el(html) {
    var t = document.createElement("template");
    t.innerHTML = html.trim();
    return t.content.firstElementChild;
  }

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  function wazeLink(uuid) { return "https://waze.com/ul?acvp=" + encodeURIComponent(uuid); }

  track("site_view", {
    utm_source: utm.utm_source, utm_medium: utm.utm_medium,
    utm_campaign: utm.utm_campaign, device: device, inapp: inapp
  });

  if (inapp && window.isPhone) document.getElementById("inapp").hidden = false;

  /* ---------------- audio ---------------- */

  var current = null;

  function stop() {
    if (!current) return;
    current.audio.pause();
    current.audio.currentTime = 0;
    current.button.classList.remove("on");
    current.card.classList.remove("playing");
    current = null;
  }

  function play(card, button, voice, clip, said) {
    var same = current && current.button === button;
    stop();
    if (same) return;
    var audio = button._audio || (button._audio = new Audio("audio/" + voice.slug + "-" + clip + ".mp3"));
    audio.onended = function () {
      button.classList.remove("on");
      // The face stops talking; the words stay so they can still be read.
      card.classList.remove("playing");
      current = null;
    };
    current = { audio: audio, button: button, card: card };
    button.classList.add("on");
    card.classList.add("playing");
    card.querySelector(".said").textContent = said ? "“" + said + "”" : "";
    audio.play().catch(function () {});
    track("preview_play", { character: voice.slug, clip: clip });
  }

  /* ---------------- did it work? ---------------- */

  var ask = document.getElementById("ask");
  var wentAway = false;

  function askAbout(pending) {
    if (!pending) return;
    document.getElementById("ask-name").textContent = "Did " + pending.name + " install?";
    ask.hidden = false;
  }

  function answer(value) {
    var pending = store(true);
    if (pending) track("install_worked", { character: pending.slug, worked: value, device: device, inapp: inapp });
    store(false, null);
    if (value === "no") {
      ask.innerHTML = '<p><b>Sorry about that.</b> The usual fixes take ten seconds.</p>' +
        '<a class="btn" href="install.html">See what to try ' + ARROW + "</a>";
      return;
    }
    ask.hidden = true;
  }

  ask.addEventListener("click", function (e) {
    var target = e.target.closest("[data-answer]");
    if (target) answer(target.getAttribute("data-answer"));
    if (e.target.closest(".close")) { ask.hidden = true; }
  });

  // The moment to ask is when they come back from Waze, not on some later visit.
  document.addEventListener("visibilitychange", function () {
    var pending = store(true);
    if (!pending) return;
    if (document.hidden) { wentAway = true; return; }
    if (wentAway) askAbout(pending);
  });
  // If the tap navigated to Waze's web page instead, Back restores this page.
  window.addEventListener("pageshow", function (e) {
    if (e.persisted) askAbout(store(true));
  });

  // Fallback: they installed, closed everything, and came back another day.
  (function () {
    var pending = store(true);
    if (!pending) return;
    if (Date.now() - (pending.at || 0) > PENDING_MAX_AGE) { store(false, null); return; }
    askAbout(pending);
  })();

  /* ---------------- cards ---------------- */

  function card(voice, lines) {
    var said = lines[voice.slug] || {};
    var clips = CLIPS.map(function (c) {
      return '<button class="clip" type="button" data-clip="' + c.id + '" aria-label="Play ' +
        escapeHtml(voice.name) + ": " + c.cap + '">' +
        '<svg viewBox="0 0 24 24" aria-hidden="true">' + c.icon + "</svg>" +
        '<span class="cap">' + c.cap + "</span></button>";
    }).join("");

    var action = window.isPhone
      ? '<a class="install" href="' + wazeLink(voice.uuid) + '">Install in Waze ' + ARROW + "</a>"
      : '<button class="install ghost qr-toggle" type="button" aria-expanded="false">Install on your phone</button>' +
        '<div class="qr" hidden><img alt="QR code to install ' + escapeHtml(voice.name) +
        ' in Waze" width="136" height="136" loading="lazy" src="qr/' + voice.slug + '.svg">' +
        "<p><strong>Scan with your phone camera.</strong>Waze opens and offers the voice. " +
        "Needs the Waze app on that phone.</p></div>";

    // A sticker face on the character's colour, with a label card under it.
    // Colours come from characters.css and the face from faces/, both keyed
    // on the slug.
    var node = el(
      '<li class="voice" id="' + voice.slug + '">' +
        '<div class="stage" aria-hidden="true">' +
          '<img class="face" alt="" width="160" height="160" src="faces/' + voice.slug + '.svg">' +
          '<span class="tag">' + escapeHtml(voice.name) + "</span>" +
        "</div>" +
        '<div class="label">' +
          "<h3 class=\"sr-only\">" + escapeHtml(voice.name) + "</h3>" +
          '<p class="blurb">' + escapeHtml(voice.blurb) + "</p>" +
          '<div class="clips">' + clips + "</div>" +
          '<p class="said" aria-live="polite"></p>' +
          action +
        "</div>" +
      "</li>"
    );

    node.querySelectorAll(".clip").forEach(function (button) {
      var clip = button.getAttribute("data-clip");
      button.addEventListener("click", function () { play(node, button, voice, clip, said[clip]); });
    });

    var install = node.querySelector("a.install");
    if (install) {
      // Native navigation, deliberately not delayed for analytics: iOS only
      // hands a link to an app when the navigation comes straight from a tap.
      install.addEventListener("click", function () {
        stop();
        store(false, { slug: voice.slug, name: voice.name, at: Date.now() });
        wentAway = false;
        track("install_click", { character: voice.slug, via: "button", device: device, inapp: inapp });
      });
    }

    var toggle = node.querySelector(".qr-toggle");
    if (toggle) {
      var shown = false;
      toggle.addEventListener("click", function () {
        var panel = node.querySelector(".qr");
        panel.hidden = !panel.hidden;
        toggle.setAttribute("aria-expanded", String(!panel.hidden));
        if (!panel.hidden && !shown) {
          shown = true;
          track("install_qr_shown", { character: voice.slug });
        }
      });
    }
    return node;
  }

  function render(voices, lines) {
    var list = document.getElementById("voice-list");
    list.innerHTML = "";
    voices.forEach(function (v) { list.appendChild(card(v, lines)); });

    // The hero lineup. Each face jumps to its card and lights it.
    var cast = document.getElementById("cast");
    voices.forEach(function (v) {
      var a = el('<a href="#' + v.slug + '" id="cast-' + v.slug + '" aria-label="' + escapeHtml(v.name) + '">' +
        '<img alt="" width="120" height="120" src="faces/' + v.slug + '.svg"></a>');
      // The cast sits outside the card, so it borrows the card's colour here.
      a.style.setProperty("--bg", getComputedStyle(document.getElementById(v.slug)).getPropertyValue("--bg"));
      a.addEventListener("click", function () {
        document.querySelectorAll(".voice.picked").forEach(function (c) { c.classList.remove("picked"); });
        document.getElementById(v.slug).classList.add("picked");
        track("cast_click", { character: v.slug });
      });
      cast.appendChild(a);
    });

    // backseatnav.com/#bugs-bunny lands on that voice: one link per character post.
    var slug = decodeURIComponent(location.hash.slice(1));
    var target = slug && document.getElementById(slug);
    if (target && target.classList.contains("voice")) {
      target.classList.add("picked");
      target.scrollIntoView({ block: "center" });
    }
  }

  function json(url) {
    return fetch(url, { cache: "no-cache" }).then(function (r) {
      if (!r.ok) throw new Error(url + " " + r.status);
      return r.json();
    });
  }

  Promise.all([json("voices.json"), json("audio/lines.json").catch(function () { return {}; })])
    .then(function (both) { render(both[0].voices, both[1]); })
    .catch(function () {
      document.getElementById("voice-list").innerHTML =
        '<li class="voice"><p class="blurb">The voices didn\'t load. Refresh, or use the ' +
        '<a href="install.html">install guide</a>.</p></li>';
    });

  /* ---------------- signup and github ---------------- */

  var form = document.getElementById("signup");
  form.addEventListener("submit", function () {
    track("signup", { device: device });
    // The form posts into a hidden frame so nobody leaves the page. Buttondown
    // may refuse to render inside a frame; the subscription still lands.
    setTimeout(function () {
      form.hidden = true;
      document.getElementById("signup-done").hidden = false;
    }, 600);
  });

  document.getElementById("github").addEventListener("click", function (e) {
    var href = this.href;
    if (e.metaKey || e.ctrlKey || e.shiftKey || e.button === 1) {
      track("github_click", {});
      return;
    }
    e.preventDefault();
    track("github_click", {}, function () { location.href = href; });
  });
})();
