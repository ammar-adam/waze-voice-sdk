/* Backseat. Renders the voices from voices.json, plays previews, installs.

   voices.json is the single source for every UUID. lines.json is generated by
   scripts/build_previews.py from the live presets, so the words shown under a
   playing clip are the words the pack actually says. */

(function () {
  "use strict";

  var PENDING_KEY = "backseat.pending";
  var PENDING_MAX_AGE = 7 * 24 * 3600 * 1000;

  var CLIPS = [
    { id: "start", cap: "Starting a drive",
      icon: '<path d="M7 4v16l13-8z"/>' },
    { id: "reroute", cap: "Recalculating",
      icon: '<path d="M20 11a8 8 0 1 0-2.3 5.7"/><path d="M20 4v7h-7"/>' },
    { id: "arrive", cap: "Arrived",
      icon: '<path d="M12 21s-6-5.4-6-10a6 6 0 0 1 12 0c0 4.6-6 10-6 10z"/><circle cx="12" cy="11" r="2"/>' }
  ];

  var ARROW = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h13"/><path d="m12 6 6 6-6 6"/></svg>';

  var params = new URLSearchParams(location.search);
  var utm = {
    utm_source: params.get("utm_source") || "",
    utm_medium: params.get("utm_medium") || "",
    utm_campaign: params.get("utm_campaign") || ""
  };
  var device = window.isPhone ? "phone" : "desktop";
  var inapp = window.inAppBrowser || "";

  // The install waiting on a "Did it work?" answer. Anything in storage that
  // isn't the shape this page wrote (an old version, an extension, a hand
  // edit) reads as nothing pending.
  function store(get, value) {
    try {
      if (get) {
        var p = JSON.parse(localStorage.getItem(PENDING_KEY) || "null");
        return p && typeof p === "object" && typeof p.slug === "string" &&
          typeof p.name === "string" && typeof p.at === "number" ? p : null;
      }
      if (value === null) localStorage.removeItem(PENDING_KEY);
      else localStorage.setItem(PENDING_KEY, JSON.stringify(value));
    } catch (e) { return null; }
    return null;
  }

  function el(html) {
    var t = document.createElement("template");
    t.innerHTML = html.trim();
    return t.content.firstElementChild;
  }

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  function wazeLink(uuid) { return "https://waze.com/ul?acvp=" + encodeURIComponent(uuid); }

  track("site_view", {
    utm_source: utm.utm_source, utm_medium: utm.utm_medium,
    utm_campaign: utm.utm_campaign, device: device, inapp: inapp
  });

  if (inapp && window.isPhone) document.getElementById("inapp").hidden = false;

  /* ---------------- audio ---------------- */

  var current = null;
  var TALKS = ["rock", "nod", "turn", "bob", "tilt"];

  function stop() {
    if (!current) return;
    current.audio.pause();
    current.audio.currentTime = 0;
    current.button.classList.remove("on");
    current.card.classList.remove("playing");
    current = null;
  }

  function play(card, button, voice, clip, said) {
    var same = current && current.button === button;
    stop();
    if (same) return;
    var audio = button._audio || (button._audio = new Audio("audio/" + voice.slug + "-" + clip + ".mp3"));
    audio.onended = function () {
      button.classList.remove("on");
      // The face stops talking; the words stay so they can still be read.
      card.classList.remove("playing");
      current = null;
    };
    current = { audio: audio, button: button, card: card };
    button.classList.add("on");
    // A different way of talking each time: nod, turn, bob, tilt or rock.
    var face = card.querySelector(".face");
    if (face) face.dataset.move = TALKS[Math.floor(Math.random() * TALKS.length)];
    card.classList.add("playing");
    card.querySelector(".said").textContent = said ? "“" + said + "”" : "";
    audio.play().catch(function () {});
    track("preview_play", { character: voice.slug, clip: clip });
    track("character_click", { character: voice.slug, action: "preview" });
  }

  /* ---------------- did it work? ---------------- */

  var ask = document.getElementById("ask");
  var wentAway = false;

  function askAbout(pending) {
    if (!pending) return;
    document.getElementById("ask-name").textContent = "Did " + pending.name + " install?";
    ask.hidden = false;
  }

  function answer(value) {
    var pending = store(true);
    if (pending) track("install_worked", { character: pending.slug, worked: value, device: device, inapp: inapp });
    store(false, null);
    if (value === "no") {
      ask.innerHTML = '<p><b>Sorry about that.</b> The usual fixes take ten seconds.</p>' +
        '<a class="btn" href="install.html">See what to try ' + ARROW + "</a>";
      return;
    }
    ask.hidden = true;
  }

  ask.addEventListener("click", function (e) {
    var target = e.target.closest("[data-answer]");
    if (target) answer(target.getAttribute("data-answer"));
    if (e.target.closest(".close")) { ask.hidden = true; }
  });

  // The moment to ask is when they come back from Waze, not on some later visit.
  document.addEventListener("visibilitychange", function () {
    var pending = store(true);
    if (!pending) return;
    if (document.hidden) { wentAway = true; return; }
    if (wentAway) askAbout(pending);
  });
  // If the tap navigated to Waze's web page instead, Back restores this page.
  window.addEventListener("pageshow", function (e) {
    if (e.persisted) askAbout(store(true));
  });

  // Fallback: they installed, closed everything, and came back another day.
  (function () {
    var pending = store(true);
    if (!pending) return;
    if (Date.now() - (pending.at || 0) > PENDING_MAX_AGE) { store(false, null); return; }
    askAbout(pending);
  })();

  /* ---------------- install steps sheet (phones) ---------------- */
  // Tapping Install in Waze on a phone opens three short steps and a real
  // Open Waze link. The link is a plain <a>: iOS only hands a link to an app
  // when the navigation comes straight from a tap, so nothing here delays it.

  var sheet = document.getElementById("install-sheet");
  var sheetPanel = sheet.querySelector(".sheet");
  var sheetGo = document.getElementById("sheet-go");
  var sheetVoice = null;
  var sheetOpener = null;
  var isAndroid = /android/i.test(navigator.userAgent || "");

  // Only the steps for this phone: Android, or iPhone and iPad.
  sheet.querySelectorAll("[data-os]").forEach(function (node) {
    var os = node.getAttribute("data-os");
    node.hidden = isAndroid ? os === "ios" : os === "android";
  });
  if (inapp) document.getElementById("sheet-inapp").hidden = false;

  function focusables() {
    return Array.prototype.filter.call(
      sheetPanel.querySelectorAll("a[href], button:not([disabled])"),
      function (n) { return n.offsetParent !== null; }
    );
  }

  function openSheet(voice, opener) {
    sheetVoice = voice;
    sheetOpener = opener;
    sheet.querySelectorAll("[data-sheet-name]").forEach(function (n) { n.textContent = voice.name; });
    var face = sheet.querySelector(".sheet-face");
    face.src = "faces/" + voice.slug + ".svg";
    // The sheet borrows the character's colours from its card.
    var colours = getComputedStyle(document.getElementById(voice.slug));
    ["--bg", "--tone", "--tone-ink"].forEach(function (p) {
      sheetPanel.style.setProperty(p, colours.getPropertyValue(p));
    });
    sheetGo.href = wazeLink(voice.uuid);
    sheet.hidden = false;
    document.documentElement.classList.add("sheet-open");
    sheetPanel.focus();
  }

  function closeSheet() {
    if (sheet.hidden) return;
    sheet.hidden = true;
    document.documentElement.classList.remove("sheet-open");
    if (sheetOpener) sheetOpener.focus();
    sheetOpener = null;
  }

  sheetGo.addEventListener("click", function () {
    var voice = sheetVoice;
    if (!voice) return;
    store(false, { slug: voice.slug, name: voice.name, at: Date.now() });
    wentAway = false;
    // One event for every way a voice gets downloaded, per character.
    track("download", { character: voice.slug, method: "tap" });
    // Let the tap's navigation start before the sheet goes.
    setTimeout(closeSheet, 400);
  });

  sheet.addEventListener("click", function (e) {
    if (e.target === sheet || e.target.closest("[data-sheet-close]")) closeSheet();
  });

  document.addEventListener("keydown", function (e) {
    if (sheet.hidden) return;
    if (e.key === "Escape") { e.preventDefault(); closeSheet(); return; }
    if (e.key !== "Tab") return;
    // Keep Tab inside the sheet while it is open.
    var items = focusables();
    if (!items.length) return;
    var first = items[0], last = items[items.length - 1];
    if (e.shiftKey && (document.activeElement === first || document.activeElement === sheetPanel)) {
      e.preventDefault(); last.focus();
    } else if (!e.shiftKey && document.activeElement === last) {
      e.preventDefault(); first.focus();
    }
  });

  /* ---------------- cards ---------------- */

  // Phones show the voices as a two-up grid of faces; tapping one opens its
  // full card (clips, the line it said, Install) across both columns. One open
  // at a time. On wide screens every card is always open and this is inert.
  function openCard(node) {
    document.querySelectorAll(".voice.open").forEach(function (c) {
      if (c === node) return;
      c.classList.remove("open");
      c.querySelector(".peek").setAttribute("aria-expanded", "false");
    });
    if (!node) return;
    node.classList.add("open");
    node.querySelector(".peek").setAttribute("aria-expanded", "true");
    requestAnimationFrame(function () { node.scrollIntoView({ block: "nearest", behavior: "smooth" }); });
  }

  function card(voice, lines) {
    var said = lines[voice.slug] || {};
    var clips = CLIPS.map(function (c) {
      return '<button class="clip" type="button" data-clip="' + c.id + '" aria-label="Play ' +
        escapeHtml(voice.name) + ": " + c.cap + '">' +
        '<svg viewBox="0 0 24 24" aria-hidden="true">' + c.icon + "</svg>" +
        '<span class="cap">' + c.cap + "</span></button>";
    }).join("");

    var action = window.isPhone
      ? '<a class="install" href="' + wazeLink(voice.uuid) + '" aria-haspopup="dialog">Install in Waze ' + ARROW + "</a>"
      : '<button class="install ghost qr-toggle" type="button" aria-expanded="false">Install on your phone</button>' +
        '<div class="qr" hidden><img alt="QR code to install ' + escapeHtml(voice.name) +
        ' in Waze" width="136" height="136" loading="lazy" src="qr/' + voice.slug + '.svg">' +
        "<p><strong>Scan with your phone camera.</strong>Waze opens and offers the voice. " +
        "Needs the Waze app on that phone.</p></div>";

    // A sticker face on the character's colour, with a label card under it.
    // Colours come from characters.css and the face from faces/, both keyed
    // on the slug.
    var node = el(
      '<li class="voice" id="' + voice.slug + '">' +
        '<div class="stage" aria-hidden="true">' +
          '<img class="face" alt="" width="160" height="160" src="faces/' + voice.slug + '.svg">' +
          '<span class="tag">' + escapeHtml(voice.name) + "</span>" +
        "</div>" +
        '<button class="peek" type="button" aria-expanded="false" aria-label="Show ' +
          escapeHtml(voice.name) + '"></button>' +
        '<div class="label">' +
          "<h3 class=\"sr-only\">" + escapeHtml(voice.name) + "</h3>" +
          '<p class="blurb">' + escapeHtml(voice.blurb) + "</p>" +
          '<div class="clips">' + clips + "</div>" +
          '<p class="said" aria-live="polite"></p>' +
          action +
        "</div>" +
      "</li>"
    );

    node.querySelector(".peek").addEventListener("click", function () {
      var opening = !node.classList.contains("open");
      openCard(opening ? node : null);
      if (opening) track("character_click", { character: voice.slug, action: "open" });
    });

    node.querySelectorAll(".clip").forEach(function (button) {
      var clip = button.getAttribute("data-clip");
      button.addEventListener("click", function () { play(node, button, voice, clip, said[clip]); });
    });

    var install = node.querySelector("a.install");
    if (install) {
      // On a phone the button opens the three steps first; the sheet's own
      // Open Waze link is the tap that hands the voice to Waze. The href
      // stays real, so a long-press or a failed script still installs.
      install.addEventListener("click", function (e) {
        if (e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
        e.preventDefault();
        stop();
        track("install_click", { character: voice.slug, via: "button", device: device, inapp: inapp });
        openSheet(voice, install);
      });
    }

    var toggle = node.querySelector(".qr-toggle");
    if (toggle) {
      var shown = false;
      toggle.addEventListener("click", function () {
        var panel = node.querySelector(".qr");
        panel.hidden = !panel.hidden;
        toggle.setAttribute("aria-expanded", String(!panel.hidden));
        if (!panel.hidden && !shown) {
          shown = true;
          track("install_qr_shown", { character: voice.slug });
          track("download", { character: voice.slug, method: "qr" });
        }
      });
    }
    return node;
  }

  function render(voices, lines) {
    var list = document.getElementById("voice-list");
    list.innerHTML = "";
    voices.forEach(function (v) { list.appendChild(card(v, lines)); });

    // The hero lineup. Each face jumps to its card and lights it.
    var cast = document.getElementById("cast");
    voices.forEach(function (v) {
      var a = el('<a href="#' + v.slug + '" id="cast-' + v.slug + '" aria-label="' + escapeHtml(v.name) + '">' +
        '<img alt="" width="120" height="120" src="faces/' + v.slug + '.svg"></a>');
      // The cast sits outside the card, so it borrows the card's colour here.
      a.style.setProperty("--bg", getComputedStyle(document.getElementById(v.slug)).getPropertyValue("--bg"));
      a.addEventListener("click", function () {
        document.querySelectorAll(".voice.picked").forEach(function (c) { c.classList.remove("picked"); });
        document.getElementById(v.slug).classList.add("picked");
        openCard(document.getElementById(v.slug));
        track("cast_click", { character: v.slug });
        track("character_click", { character: v.slug, action: "face" });
      });
      cast.appendChild(a);
    });

    // backseatnav.com/#bugs-bunny lands on that voice: one link per character post.
    // A malformed hash (#%E0) makes decodeURIComponent throw; it must not
    // take the voice list down with it.
    var slug = "";
    try { slug = decodeURIComponent(location.hash.slice(1)); } catch (e) { slug = ""; }
    var target = slug && document.getElementById(slug);
    if (target && target.classList.contains("voice")) {
      target.classList.add("picked");
      openCard(target);
      target.scrollIntoView({ block: "center" });
    }
  }

  function json(url) {
    return fetch(url, { cache: "no-cache" }).then(function (r) {
      if (!r.ok) throw new Error(url + " " + r.status);
      return r.json();
    });
  }

  Promise.all([json("voices.json"), json("audio/lines.json").catch(function () { return {}; })])
    .then(function (both) { render(both[0].voices, both[1]); })
    .catch(function () {
      document.getElementById("voice-list").innerHTML =
        '<li class="voice"><p class="blurb">The voices didn\'t load. Refresh, or use the ' +
        '<a href="install.html">install guide</a>.</p></li>';
    });

  /* ---------------- install steps, by device ---------------- */

  document.querySelectorAll("[data-device]").forEach(function (node) {
    node.hidden = node.getAttribute("data-device") !== (window.isPhone ? "phone" : "desktop");
  });

  /* GitHub links are tracked site-wide by track.js. */

  /* ---------------- who should ride next? ---------------- */
  // Backed by /api/suggestions (api/suggestions.js), which stores every
  // suggestion in Redis and folds different spellings into one entry. The
  // chips under the box are the four most wanted; tapping one backs it.
  // Until the store is connected the endpoint answers 503, and suggestions
  // go to GitHub instead.

  var VOTED_KEY = "backseat.voted";
  var TOP = 4;
  var MIN_SHOWN = 10;
  // Shown when the board can't be read, so the chips are never empty.
  var FALLBACK = [
    { key: "spongebob", name: "SpongeBob" }, { key: "yoda", name: "Yoda" },
    { key: "shrek", name: "Shrek" }, { key: "homersimpson", name: "Homer Simpson" }
  ];
  var board = document.getElementById("board");
  var note = document.getElementById("suggest-note");
  var suggestForm = document.getElementById("suggest-form");
  var suggestName = document.getElementById("suggest-name");
  var toastNode = document.getElementById("toast");
  var ISSUE = "https://github.com/ammar-adam/waze-voice-sdk/issues/new?labels=voice-request&title=";
  var toastTimer = null;

  // A status region that is always in the page, so screen readers announce
  // each new message; empty, it is invisible.
  function toast(text, kind) {
    toastNode.textContent = text;
    toastNode.className = "toast sticker" + (kind ? " " + kind : "");
    clearTimeout(toastTimer);
    toastTimer = setTimeout(function () { toastNode.textContent = ""; }, 3600);
  }

  function voted() {
    try {
      var list = JSON.parse(localStorage.getItem(VOTED_KEY) || "[]");
      return Array.isArray(list) ? list.filter(function (k) { return typeof k === "string"; }) : [];
    } catch (e) { return []; }
  }
  function remember(key) {
    try {
      var list = voted();
      if (list.indexOf(key) < 0) list.push(key);
      localStorage.setItem(VOTED_KEY, JSON.stringify(list));
    } catch (e) {}
  }
  // The same key the server makes, near enough to catch a repeat before it's sent.
  function keyOf(name) {
    var s = String(name);
    if (s.normalize) s = s.normalize("NFKD").replace(/[\u0300-\u036f]/g, "");
    return s.toLowerCase().replace(/&/g, " and ").trim().replace(/^the\s+/, "").replace(/[^a-z0-9]+/g, "");
  }

  function drawBoard(items) {
    var mine = voted();
    board.innerHTML = "";
    (items && items.length ? items : FALLBACK).slice(0, TOP).forEach(function (item) {
      var done = mine.indexOf(item.key) >= 0;
      // A count under MIN_SHOWN reads as an empty room, so it stays hidden.
      var count = typeof item.votes === "number" && item.votes >= MIN_SHOWN;
      var li = el(
        '<li><button class="chip' + (done ? " done" : "") + '" type="button"' +
        ' aria-label="' + (done ? "You backed " : "Back ") + escapeHtml(item.name) +
        (count ? ", " + item.votes + (item.votes === 1 ? " vote" : " votes") : "") + '"' +
        (done ? ' aria-disabled="true"' : "") + ">" +
        '<span class="who">' + escapeHtml(item.name) + "</span>" +
        '<span class="n" aria-hidden="true">' +
        (done
          ? '<svg viewBox="0 0 24 24"><path d="m5 12 5 5 9-10"/></svg>'
          : '<svg viewBox="0 0 24 24"><path d="m6 14 6-6 6 6"/></svg>') +
        (count ? item.votes : "") + "</span></button></li>"
      );
      li.querySelector(".chip").addEventListener("click", function () {
        if (done) { toast("You've already backed " + item.name + "."); return; }
        send(item.name);
      });
      board.appendChild(li);
    });
  }

  // Built from nodes, not HTML: the name is whatever the visitor typed.
  function offline(name) {
    var link = document.createElement("a");
    link.href = ISSUE + encodeURIComponent("Voice request: " + (name || ""));
    link.textContent = "suggest it on GitHub";
    note.textContent = "Suggestions open soon. Meanwhile, ";
    note.appendChild(link);
    note.appendChild(document.createTextNode("."));
  }

  function send(name) {
    var key = keyOf(name);
    if (key && voted().indexOf(key) >= 0) { toast("You've already backed " + name + "."); return; }
    fetch("api/suggestions", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ name: name })
    }).then(function (r) {
      return r.json().catch(function () { return {}; })
        .then(function (body) { return { ok: r.ok, status: r.status, body: body || {} }; });
    }).then(function (res) {
      if (res.status === 503) { offline(name); toast("Suggestions aren't open yet. Try GitHub for now.", "bad"); return; }
      if (!res.ok) { toast(res.body.error || "That didn't go through. Try again.", "bad"); return; }
      note.textContent = "";
      if (res.body.live) {
        toast("Already riding: " + res.body.live + ". Scroll up to install it.");
        return;
      }
      var added = res.body.added || { key: key, name: name };
      remember(key);
      remember(added.key);
      // The server counts one vote per network per character a day.
      toast(res.body.counted === false
        ? "You've already backed " + added.name + " today."
        : "Suggestion added: " + added.name, "good");
      drawBoard(res.body.items);
      // Only a vote the server counted moves the "suggested" number on stats.
      if (res.body.counted !== false) track("suggest", { character: added.key });
    }).catch(function () {
      offline(name);
      toast("That didn't go through. Check your connection and try again.", "bad");
    });
  }

  suggestForm.addEventListener("submit", function (e) {
    e.preventDefault();
    var name = suggestName.value.trim();
    if (name.length < 2) { toast("Type a character's name first.", "bad"); suggestName.focus(); return; }
    suggestName.value = "";
    send(name);
  });

  drawBoard(null);
  fetch("api/suggestions?limit=" + TOP, { cache: "no-cache" }).then(function (r) {
    if (r.status === 503 || !r.ok) throw new Error("offline");
    return r.json();
  }).then(function (body) { drawBoard(body.items); }).catch(function () { drawBoard(null); });

  /* ---------------- every now and then, somebody moves ---------------- */
  // Faces idle, and once in a while one of them hops, nods, turns or wiggles.
  // Random face, random move, random gap, so it never loops.

  // Four moves per character, chosen to suit them. Every move is picked at
  // random from the character's set, never the same one twice in a row, so
  // nobody is stuck with one trick. A full spin is a lot to look at, so it
  // is rare: WEIGHTS keeps it under one move in twenty.
  var SETS = {
    "bugs-bunny": ["lean", "hop", "wiggle", "tilt"],
    "cookie-monster": ["chomp", "bounce", "wiggle", "shake"],
    "daffy-duck": ["shake", "hop", "spin", "squash"],
    "elmo": ["bounce", "wiggle", "spin", "nod"],
    "tigger": ["bounce", "pounce", "spin", "hop"],
    "pooh": ["sway", "nod", "tilt", "squash"],
    "paddington": ["tilt", "nod", "hop", "sway"],
    "mickey-mouse": ["hop", "spin", "wiggle", "tilt"],
    "darth-vader": ["pulse", "turn", "nod", "lean"],
    "batman": ["turn", "lean", "nod", "pulse"],
    "gordon-ramsay": ["shake", "squash", "nod", "turn"],
    "eric-cartman": ["squash", "shake", "spin", "wiggle"]
  };
  var DEFAULT_SET = ["spin", "hop", "nod", "wiggle"];
  // Relative odds; anything not listed is 1. With three or four other moves
  // to pick from, 0.1 puts a spin at 3 to 5 percent of moves.
  var WEIGHTS = { spin: 0.1 };
  var still = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  function pick(choices) {
    var weight = function (m) { return m in WEIGHTS ? WEIGHTS[m] : 1; };
    var total = choices.reduce(function (sum, m) { return sum + weight(m); }, 0);
    var roll = Math.random() * total;
    for (var i = 0; i < choices.length; i++) {
      roll -= weight(choices[i]);
      if (roll < 0) return choices[i];
    }
    return choices[choices.length - 1];
  }

  function slugOf(node) {
    var holder = node.closest("[id]");
    return holder ? holder.id.replace(/^cast-/, "") : "";
  }

  function move(face) {
    if (!face || face.dataset.moving) return;
    var set = SETS[slugOf(face)] || DEFAULT_SET;
    var choices = set.filter(function (m) { return m !== face.dataset.lastMove; });
    var name = pick(choices);
    face.dataset.moving = "1";
    face.dataset.lastMove = name;
    face.classList.add("move-" + name);
    face.addEventListener("animationend", function done() {
      face.classList.remove("move-" + name);
      delete face.dataset.moving;
      face.removeEventListener("animationend", done);
    });
  }

  // Hover: whoever you point at does one of their moves.
  document.addEventListener("mouseover", function (e) {
    if (still) return;
    var target = e.target.closest(".cast a, .voice .stage");
    if (!target || target.contains(e.relatedTarget)) return;
    var face = target.querySelector("img");
    if (face && !face.closest(".voice.playing")) move(face);
  });

  function onScreen(node) {
    var r = node.getBoundingClientRect();
    return r.bottom > 0 && r.top < window.innerHeight;
  }

  // And every now and then, somebody fidgets on their own.
  function fidget() {
    var faces = Array.prototype.slice.call(document.querySelectorAll(".cast img, .voice:not(.playing) .face"))
      .filter(onScreen);
    if (faces.length && !document.hidden) move(faces[Math.floor(Math.random() * faces.length)]);
    setTimeout(fidget, 1800 + Math.random() * 3200);
  }
  if (!still) setTimeout(fidget, 1500);
})();
